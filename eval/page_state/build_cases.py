"""Page-state test set: every real sandbox observation in eval/real/raw/obs (+ a few hand-written provider pages).

Ground truth: loaded | challenge | blocked | host_warning | unavailable (contracts/gemma_page_state.txt).
Labels of real pages come from the rules below plus a reviewed override table for the ambiguous ones.
Synthetic pages (source=synthetic) imitate other vendors' pages to test generalisation; they are written here.
usage: python eval/page_state/build_cases.py  ->  eval/page_state/cases.jsonl
"""
import glob, json, re, sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[2]
OBS = ROOT / "eval/real/raw/obs"
sys.path[:0] = [str(ROOT / "eval"), str(ROOT / "backend")]
from anon_ids import anon_id, scrub  # noqa: E402  (mal_<domain> -> mal_NNN, map in eval/real/raw/)
from redflag_backend import psl  # noqa: E402
PLATFORMS = json.dumps(json.load(open(ROOT / "contracts/gate_lists.json")))  # shared hosts stay readable


def own_domains(o):
    """The phishing page's own host + registrable domain (not shared platforms), to scrub from its text."""
    h = (urlsplit(o.get("requested_url") or "").hostname or "").lower()
    r = psl.registrable_domain(h) if h else None
    return [d for d in (h, r) if d and f'"{d}"' not in PLATFORMS]

OVERRIDE = {  # reviewed by hand (texts read 2026-11-04)
    "mal_096": "loaded",            # 200 "Document Viewing Error": a lure that only claims an error
    "mal_099": "loaded",            # 404 "Order cancelled by the seller": scam content served with 404
    "mal_012": "blocked",   # 200 "Error 406": ModSecurity refused the request
    "mal_021": "unavailable",  # 403 JSON "account_trouble": hosting account disabled
    "ben_assessorhub_net": "blocked",      # 403 "The request is blocked." (Azure Front Door)
    "mal_039": "unavailable",  # 404 "This app isn't live yet"
}

def label(name, o):
    if name in OVERRIDE:
        return OVERRIDE[name]
    t = (o.get("title") or "").strip()
    st = o.get("status") or 0
    if re.search(r"Suspected (Phishing|Malware) \| Cloudflare", t): return "host_warning"
    if t == "Just a moment...": return "challenge"
    if t.startswith("Attention Required!") or t == "403 Forbidden": return "blocked"
    if st >= 500 or st in (404, 410, 451): return "unavailable"
    if st >= 400: raise ValueError(f"unlabelled {name} {st} {t!r}")
    return "loaded"

def page_of(o):
    forms = o.get("forms") or []
    pw = any(f.get("type") == "password" for fm in forms for f in (fm.get("fields") or []))
    return {"http_status": o.get("status"), "title": (o.get("title") or "").strip()[:120],
            "text": " ".join((o.get("visible_text") or "").split())[:600],
            "form_count": len(forms), "has_password_field": pw}

