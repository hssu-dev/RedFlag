cases = []
for f in sorted(glob.glob(str(OBS / "*.json"))):
    name = anon_id(Path(f).stem)
    o = json.load(open(f))
    if not o.get("ok"):
        continue  # load failures: code knows (no page to judge)
    if name.startswith("mal_"):  # keep live phishing domains out of the committed cases
        doms = own_domains(o)
        o = {**o, "title": scrub(o.get("title") or "", doms), "visible_text": scrub(o.get("visible_text") or "", doms)}
    cases.append({"id": name, "source": "real", "label": label(name, o), "page": page_of(o)})
for cid, lab, page in SYNTH:
    cases.append({"id": cid, "source": "synthetic", "label": lab, "page": page})
out = ROOT / "eval/page_state/cases.jsonl"
out.write_text("".join(json.dumps(c, ensure_ascii=False) + "\n" for c in cases), encoding="utf-8")
from collections import Counter
print(len(cases), Counter((c["source"], c["label"]) for c in cases))
